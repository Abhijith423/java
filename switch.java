public class swit{
    public static void main(String [] args)
    {
        int a=3;
        switch(a){
            case 1:
                System.out.println("ONE");
                break;
            case 2:
                System.out.println("TWO");
                break;
            case 3:
                System.out.println("THREE");
                break;
            default:
                System.out.println("Invalid");
                break;
        }
    }
}
